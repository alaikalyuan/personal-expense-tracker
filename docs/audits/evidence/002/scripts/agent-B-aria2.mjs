import { launch, newContext, login, BASE, OUT } from "./lib.mjs";
import { writeFileSync } from "node:fs";
const b = await launch(); const ctx = await newContext(b,{hasTouch:true,isMobile:true}); const page = await ctx.newPage(); await login(page,"typical");
let o="";
await page.goto(BASE+"/"); await page.waitForLoadState("networkidle");
await page.getByRole("button",{name:"Tambah pengeluaran"}).click(); await page.waitForTimeout(700);
o+="=== ADD QUICK\n"+await page.locator("[role=dialog]").ariaSnapshot()+"\n";
await page.getByRole("button",{name:"Standar",exact:true}).click(); await page.waitForTimeout(500);
o+="=== ADD STANDARD\n"+await page.locator("[role=dialog]").ariaSnapshot()+"\n";
console.log(o.slice(0,4500));
await page.goto(BASE+"/subscriptions"); await page.waitForLoadState("networkidle");
await page.getByRole("button",{name:"Tambah",exact:true}).click(); await page.waitForTimeout(600);
o+="=== SUB ADD\n"+await page.locator("[role=dialog]").ariaSnapshot()+"\n";
await ctx.close();
const c2 = await newContext(b,{hasTouch:true,isMobile:true}); const p2=await c2.newPage(); await p2.goto(BASE+"/?auth=login"); await p2.waitForLoadState("networkidle"); await p2.waitForTimeout(600);
const ls=await p2.locator("[role=dialog]").ariaSnapshot(); o+="=== LOGIN (Masuk)\n"+ls+"\n"; console.log("=== LOGIN\n"+ls);
console.log("labelledby target text:", await p2.evaluate(()=>{const d=document.querySelector("[role=dialog]"); const id=d.getAttribute("aria-labelledby"); return id+" -> "+(document.getElementById(id)?.innerText)}));
writeFileSync(OUT+"/B-aria-dialogs.txt",o);
await b.close();
